lo_integration_tests <- function(bundle,cfg,out) {
 lo_engine_boot(bundle,cfg,out,synthetic=TRUE)
 obj<-lo_fixture();q<-read.csv(file.path(bundle,'PILOT_TASKS.csv'),colClasses='character',na.strings=character(),check.names=FALSE)
 q<-lo_tasks_prepare(q,obj,bundle)
 store<-file.path(out,'synthetic_store');dir.create(out,recursive=TRUE,showWarnings=FALSE)
 checks<-list();on.exit({if(length(checks))write.csv(do.call(rbind,checks),file.path(out,'INTEGRATION_TESTS.csv'),row.names=FALSE)},add=TRUE);check<-function(name,pass){checks[[length(checks)+1L]]<<-data.frame(check=name,status=if(isTRUE(pass))'PASS'else'FAIL');if(!isTRUE(pass))stop('Integratietest mislukt: ',name)}
 fails<-function(x)inherits(tryCatch(force(x),error=function(e)e),'error')
 calls<-0L;calculate<-function(q){calls<<-calls+1L;lo_compute_one(obj,q)}
 check('interruption_after_durable_SQL_commit',fails(lo_execute(q,store,calculate,interrupt_after=1)))
 check('one_calculation_before_interruption',calls==1L)
 calls<-0L;r<-lo_execute(q,store,calculate)
 check('resume_reuses_completed_task',calls==nrow(q)-1L&&r$operations$operation[1]=='REUSE')
 f<-file.path(store,c('CURRENT_RESULTS.parquet','RESULT_HISTORY.parquet'));before<-vapply(f,function(p)digest::digest(file=p,algo='sha256'),character(1))
 calls<-0L;r2<-lo_execute(q,store,calculate)
 check('repeat_zero_calculations',calls==0L&&all(r2$operations$operation=='REUSE'))
 check('repeat_no_parquet_rewrite',identical(before,vapply(f,function(p)digest::digest(file=p,algo='sha256'),character(1))))
 altered<-q;altered$science_fingerprint[1]<-lo36_fp(list(q$science_fingerprint[1],'test_definition_change'))
 calls<-0L;r3<-lo_execute(altered,store,calculate)
 check('targeted_invalidation',calls==1L&&r3$operations$operation[1]=='COMPUTE')
 s<-lo_store_open(store);h<-lo_store_frames(s);lo_store_close(s)
 check('history_preserved',nrow(h$history)==nrow(q)+1L&&nrow(h$current)==nrow(q))
 check('single_current_per_key',!anyDuplicated(h$current$metric_key)&&all(h$current$is_current==1L))
 s<-lo_store_open(store);x<-h$current[1,,drop=FALSE];x$estimate<-x$estimate+1
 check('same_identity_conflict_rejected',fails(lo_store_put(s,x)))
 DBI::dbExecute(s$con,'UPDATE meta SET exported=-1')
 check('interruption_during_parquet_export',fails(lo_store_export(s,interrupt_after_current=TRUE)))
 lo_store_close(s)
 calls<-0L;lo_execute(altered,store,calculate)
 check('export_recovery_zero_calculations',calls==0L)
 s<-lo_store_open(store);h<-lo_store_frames(s)
 check('SQLite_integrity',identical(DBI::dbGetQuery(s$con,'PRAGMA integrity_check')[[1]],'ok'))
 check('CURRENT_matches_SQLite',lo_frame_equal(h$current,as.data.frame(arrow::read_parquet(f[1], mmap=FALSE))))
 check('HISTORY_matches_SQLite',lo_frame_equal(h$history,as.data.frame(arrow::read_parquet(f[2], mmap=FALSE))))
 check('second_writer_refused',fails(lo_store_open(store)))
 lo_store_close(s)
 estimates<-setNames(r$results$estimate,r$results$metric_key)
 b<-which(q$stat=='total_basic');l<-which(q$stat=='total_below');g<-which(q$stat=='gap')
 check('complement_identity',abs(estimates[q$metric_key[b]]+estimates[q$metric_key[l]]-1)<1e-12)
 se<-setNames(r$results$se,r$results$metric_key)
 check('gender_contrast_covariance',abs(estimates[q$metric_key[g]]-90)<1e-10&&abs(se[q$metric_key[g]]-sqrt(300))<1e-10)
 x<-as.data.frame(arrow::read_parquet(f[1], mmap=FALSE));x$estimate[1]<-999;arrow::write_parquet(x,f[1])
 check('external_edit_not_overwritten',fails(lo_execute(altered,store,calculate)))
 # Leave the deliberately corrupted fixture in its own test-only store; local pilot has another store.
 z<-do.call(rbind,checks);write.csv(z,file.path(out,'INTEGRATION_TESTS.csv'),row.names=FALSE)
 writeLines(capture.output(sessionInfo()),file.path(out,'SESSION_INFO.txt'))
 z
}
