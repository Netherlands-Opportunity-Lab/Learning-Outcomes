source('06_pipeline/BUNDLE_DISCOVERY.R')
source('06_pipeline/LO_EXISTING_RESULT_REGISTRY.R')
source('06_pipeline/LO_RUN_CONFIG.R')
source('06_pipeline/LO_PRODUCT_TRACE.R')
repo<-normalizePath('.',winslash='/')
bundle<-file.path(repo,'02_analysis/scientific_dependencies')
Sys.unsetenv(c('LO_FRESH_REPLICATION','LO05_BUNDLE','LO_RUN_CONFIG'))
stopifnot(inherits(try(lo_bundle_verify(bundle),silent=TRUE),'try-error'))
Sys.setenv(LO_FRESH_REPLICATION='1',LO_REPO_ROOT=repo)
stopifnot(isTRUE(lo_bundle_verify(bundle)),
  identical(lo_bundle_discover(),normalizePath(bundle,winslash='/')))
work<-tempfile('public_replication_');dir.create(work)
work<-normalizePath(work,winslash='/',mustWork=TRUE)
stopifnot(startsWith(work,paste0(normalizePath(tempdir(),winslash='/'),'/')))
targets<-data.frame(metric_key=c('a','b'),country='NLD',survey='PIRLS',
  year=c('2016','2021'),module='core',domain='reading',stat='mean')
# A broken legacy archive must not be touched in an explicitly fresh run.
dir.create(file.path(work,'evidence'))
writeLines('not a historical archive',file.path(work,'evidence/LO01_HISTORICAL_CANDIDATES.csv.gz'))
answer<-lo_existing_result_evidence(work,targets,file.path(work,'state'))
stopifnot(nrow(answer$evidence)==0L,identical(answer$match$metric_key,targets$metric_key),
  answer$summary$approved_to_reuse==0L,answer$summary$approved_to_compute==0L)
before<-lo_fixed_input_manifest(repo,bundle,work,'nld_only')
Sys.unsetenv('LO_FRESH_REPLICATION')
after<-lo_fixed_input_manifest(repo,bundle,work,'nld_only')
stopifnot(!identical(before$sha256,after$sha256))
# A changed manifest cannot silently become a new trusted public bundle.
Sys.setenv(LO_FRESH_REPLICATION='1')
copy<-file.path(work,'changed');dir.create(copy)
file.copy(file.path(bundle,'PUBLIC_REPLICATION_BUNDLE.json'),copy)
file.copy(file.path(bundle,'MANIFEST_SHA256.csv'),copy)
cat('\n',file=file.path(copy,'MANIFEST_SHA256.csv'),append=TRUE)
stopifnot(inherits(try(lo_bundle_verify(copy),silent=TRUE),'try-error'))
Sys.unsetenv(c('LO_FRESH_REPLICATION','LO_REPO_ROOT'))
unlink(work,recursive=TRUE)
cat('PASS public dependency identity, explicit fresh mode, no legacy candidate reads and resume fingerprint separation\n')
