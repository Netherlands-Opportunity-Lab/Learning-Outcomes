source('06_pipeline/LO_GENDER_POOL_POLICY.R')
expect_error<-function(x)stopifnot(inherits(tryCatch({force(x);NULL},error=identity),'error'))
tmp<-tempfile();dir.create(tmp);on.exit<-NULL
raw<-data.frame(CNT=rep('NLD',5),CNTSTUID=as.character(1:5),W_FSTUWT=c(1,2,3,4,1))
raw$ST004D01T<-haven::labelled(rep(99,5),c(Female=1,Male=2))
raw$MALE<-haven::labelled(c(0,1,0,1,99),c('Female / Other'=0,Male=1))
obj<-list(data=data.frame(SOURCE_STUDENT_ID=as.character(1:5),W=raw$W_FSTUWT,DEMO_GENDER=c(NA,'boy',NA,'boy',NA)),meta=list(survey='PISA',year=2025,v9_country='NLD'))
q<-data.frame(country='NLD',survey='PISA',year='2025',module=c('gender','gender','gender','extension_ses_gender'),group=c('girl','boy','girls_minus_boys','q1_girl'),metric_key=letters[1:4],calculation_policy='EXPLICIT')
support<-data.frame(country='NLD',survey='PISA',year='2025',source_path=file.path(tmp,'canonical.rds'),source_sha256='sha')
jsonlite::write_json(list(country='NLD',year=2025,canonical_sha256='sha',gender_status='PARTIAL_SOURCE_GENDER_GIRL_UNRESOLVED',source_value_labels=list(MALE=as.list(attr(raw$MALE,'labels')))),file.path(tmp,'SOURCE_VERIFICATION.json'),auto_unbox=TRUE)
pooled<-lo_gender_pool_tasks(q,support)
stopifnot(identical(pooled,lo_gender_pool_tasks(pooled,support)),identical(pooled$metric_key[2],q$metric_key[2]),all(pooled$metric_key[c(1,3,4)]!=q$metric_key[c(1,3,4)]))
mapped<-lo_gender_pool_object(obj,raw,pooled)
stopifnot(identical(mapped$data$DEMO_GENDER,c('girl','boy','girl','boy',NA_character_)))
lo_gender_pool_guard(mapped,pooled)
expect_error(lo_gender_pool_guard(mapped,q));expect_error(lo_gender_pool_guard(obj,pooled))
bad_task<-pooled;bad_task$calculation_policy<-NULL;expect_error(lo_gender_pool_guard(mapped,bad_task))
bad<-raw;attr(bad$MALE,'labels')<-c(Female=0,Male=1);expect_error(lo_gender_pool_object(obj,bad,pooled))
bad<-raw;bad$CNTSTUID[1]<-'wrong';expect_error(lo_gender_pool_object(obj,bad,pooled))
bad<-raw;bad$W_FSTUWT[1]<-2;expect_error(lo_gender_pool_object(obj,bad,pooled))
bad<-raw;bad$ST004D01T[1]<-1;expect_error(lo_gender_pool_object(obj,bad,pooled))
stopifnot(lo_gender_display(pooled$metric_key[1],'girl')=='Meisjes + other')
unlink(tmp,recursive=TRUE)
cat('PASS pooled gender identity, labels, exact-field priority, pupil/weight matching, guarded estimation and idempotence\n')

encoded_counts<-jsonlite::fromJSON(jsonlite::toJSON(mapped$meta$gender_counts,auto_unbox=TRUE))
stopifnot(identical(sort(names(encoded_counts)),sort(c('boy','girl','missing'))),encoded_counts$missing==1L)
