source("06_pipeline/LO_EXISTING_RESULT_REGISTRY.R")
work<-tempfile("lo_sources_");dir.create(work)
bundle<-file.path(work,"bundle");dir.create(bundle)
dir.create(file.path(bundle,"evidence"))
state<-file.path(work,"LO05_RESULTATEN","FIXED_PRODUCTION_V1","nld_only")
dir.create(state,recursive=TRUE)
consolidated<-file.path(work,"LO05_RESULTATEN","consolidated")
dir.create(consolidated,recursive=TRUE)
stopifnot(requireNamespace("DBI",quietly=TRUE),
          requireNamespace("RSQLite",quietly=TRUE))
con<-DBI::dbConnect(RSQLite::SQLite(),
         file.path(consolidated,"RESULT_PROVENANCE.sqlite"))
DBI::dbWriteTable(con,"result_versions",data.frame(
 metric_key="m3",estimate="470",se="5.2",scientific_status="UNVALIDATED",
 input_fingerprint=paste(rep("f",64),collapse=""),
 record_version_id="consolidated_test_version",source_id="central_current",
 source_sha256=paste(rep("a",64),collapse="")))
DBI::dbDisconnect(con)
write_gz <- function(x,p) {
  con<-gzfile(p,"wt")
  write.csv(x,con,row.names=FALSE)
  close(con)
}
write_gz(data.frame(metric_key="m1",record_version_id="older",
 action="REUSE",estimate="490",se="",scientific_status="UNVALIDATED",
 stringsAsFactors=FALSE),
 file.path(bundle,"evidence","LO01_HISTORICAL_CANDIDATES.csv.gz"))
write_gz(data.frame(metric_key="m2",record_version_id="newer",
 estimate="500",se="3",scientific_status="COMPUTED_PENDING_VALIDATION",
 input_fingerprint=paste(rep("a",64),collapse="")),
 file.path(bundle,"evidence","LO02_RETURN_20261010_CURRENT_RESULTS.csv.gz"))
write_gz(data.frame(country="iso3:NLD",survey="PISA",year="2022",
 domain="reading",stat="mean",estimate="490",se="2",
 status="validated_candidate"),
 file.path(bundle,"evidence","V8_NLD_DASHBOARD_GRID_FULL.csv.gz"))
write_gz(data.frame(country="iso3:NLD",survey="PISA",year="2022",
 domain="reading",stat="mean",estimate="490",se="2",
 status="conditional"),
 file.path(bundle,"evidence","V9_COUNTRIES_NEW_MASTER_ROWS.csv.gz"))
tasks<-data.frame(metric_key=c("m1","m2","m3"),survey="PISA",
 country="NLD",year="2022",module="core",domain="reading",
 stat=c("mean","gender_mean","mean"))
