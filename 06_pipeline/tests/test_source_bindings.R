source('06_pipeline/LO_SOURCE_BINDINGS.R')
work<-tempfile('bindings_');dir.create(work)
repo<-file.path(work,'repo');catalog<-file.path(repo,'06_pipeline/review_20261013/international')
dir.create(catalog,recursive=TRUE)
file.copy('06_pipeline/LO_ATOMIC_CHECKPOINT.R',file.path(repo,'06_pipeline/LO_ATOMIC_CHECKPOINT.R'))
raw<-file.path(work,'source.sav');haven::write_sav(data.frame(CNT=c('NLD','AUS','NLD'),CNTSTUID=1:3),raw)
sha<-digest::digest(file=raw,algo='sha256')
catalogue<-data.frame(country='NLD',survey='PISA',year='2015',raw_sha256=sha,source_country='NLD',
  allowed_grades='',population_note='Synthetic test only',population_evidence='synthetic',source_filename='source.sav',control_filename='',control_sha256='')
write.csv(catalogue,file.path(catalog,'SOURCE_CATALOG.csv'),row.names=FALSE)
homes<-data.frame(country=character(),survey=character(),year=character(),sha256=character(),source_filename=character())
write.csv(homes,file.path(catalog,'HOME_SOURCE_CATALOG.csv'),row.names=FALSE)
bindings<-file.path(work,'bindings.csv');write.csv(data.frame(sha256=sha,path=normalizePath(raw,winslash='/')),bindings,row.names=FALSE)
root<-file.path(work,'run')
manifest<-lo_bind_international_sources(repo,root,bindings)
index<-readRDS(file.path(root,'international/PISA_2015_ROW_INDEX.rds'))
stopifnot(identical(index$selector,c('NLD','AUS','NLD')),index$n==3L)
first<-digest::digest(file=manifest,algo='sha256')
lo_bind_international_sources(repo,root,bindings)
stopifnot(first==digest::digest(file=manifest,algo='sha256'))
haven::write_sav(data.frame(CNT='USA',CNTSTUID=9),raw)
stopifnot(inherits(try(lo_bind_international_sources(repo,root,bindings),silent=TRUE),'try-error'),
  first==digest::digest(file=manifest,algo='sha256'))
unlink(work,recursive=TRUE)
