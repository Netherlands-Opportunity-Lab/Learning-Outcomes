source('06_pipeline/LO_IEA_SOURCE_BLOCK.R')
source('06_pipeline/LO_ATOMIC_CHECKPOINT.R')
w<-tempfile('international_source_');dir.create(w)
d<-data.frame(IDCNTRY=276,IDSTUD=1:4,IDSCHOOL=c(1,1,2,2),IDCLASS=c(1,1,2,2),
 IDPOP=1,IDGRADE=4,ITSEX=haven::labelled(c(1,2,1,2),c(Girl=1,Boy=2)),TOTWGT=1,JKZONE=1,JKREP=c(0,0,1,1))
for(j in 1:5)d[[paste0('ASRREA',sprintf('%02d',j))]]<-500+1:4+j
f<-file.path(w,'source.sav');haven::write_sav(d,f)
x<-lo_iea_prepare_country(f,'PIRLS',2016,file.path(w,'deu'),'DEU',276L)
stopifnot(x$receipt$country=='DEU',nrow(x$object$data)==4L)
stopifnot(inherits(try(lo_iea_prepare_nld(f,'PIRLS',2016,file.path(w,'wrong')),silent=TRUE),'try-error'))
d$JKZONE<-c(1,1,1,2);haven::write_sav(d,f)
x<-lo_iea_prepare_country(f,'PIRLS',2016,file.path(w,'official_half'),'DEU',276L)
stopifnot(nrow(x$object$data)==4L,identical(x$receipt$official_zones_with_one_observed_half,'2'))
d$IDGRADE<-5;haven::write_sav(d,f)
stopifnot(inherits(try(lo_iea_prepare_country(f,'PIRLS',2016,file.path(w,'grade'),'DEU',276L),silent=TRUE),'try-error'))
stopifnot(inherits(try(lo_iea_prepare_country(f,'PIRLS',2016,file.path(w,'grade'),'DEU',276L,5L),silent=TRUE),'try-error'))
p<-file.path(w,'checkpoint.csv');lo_atomic_csv(data.frame(value=1),p);lo_atomic_csv(data.frame(value=2),p)
stopifnot(read.csv(p)$value==2L)
unlink(w,recursive=TRUE)
cat('PASS exact country identity, nonstandard grade evidence and atomic replacement\n')
